const { chromium } = require('playwright');
const out = process.argv[2] || '.';
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1400, height: 950 } });
  const errs = [];
  p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  p.on('pageerror', (e) => errs.push('PAGEERR ' + e.message));
  await p.goto('file://' + __dirname + '/../dist/seal-the-deal.html');
  await p.waitForTimeout(800);
  await p.screenshot({ path: out + '/01-title.png' });
  await p.click('[data-diff="medium"]');
  await p.waitForTimeout(400);
  await p.screenshot({ path: out + '/02-intro.png' });
  await p.click('#m-go');
  await p.waitForTimeout(300);
  await p.screenshot({ path: out + '/03-desk-dcf.png', fullPage: true });
  for (const a of ['wacc:0.25', 'wacc:0.25', 'wacc:0.25', 'tab:comps']) await p.click(`[data-act="${a}"]`);
  await p.click('[data-act="peer:5"]'); await p.click('[data-act="peer:6"]');
  await p.waitForTimeout(600);
  await p.screenshot({ path: out + '/04-comps.png', fullPage: true });
  await p.click('#btn-submit'); await p.waitForTimeout(500);
  await p.screenshot({ path: out + '/05-reject.png' });
  await p.click('#m-ok');
  // brute force to fair via engine moves
  await p.evaluate(() => { const s = window.__std; s.handle('tab:prec'); s.handle('prec:4'); s.handle('prec:5'); s.handle('tab:bridge'); s.handle('bridge:0'); });
  await p.waitForTimeout(600);
  await p.screenshot({ path: out + '/06-bridge.png', fullPage: true });
  await p.click('#btn-submit'); await p.waitForTimeout(900);
  await p.screenshot({ path: out + '/07-approve.png' });
  const mob = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true });
  mob.on('pageerror', (e) => errs.push('MOB ' + e.message));
  await mob.goto('file://' + __dirname + '/../dist/seal-the-deal.html');
  await mob.waitForTimeout(500);
  await mob.screenshot({ path: out + '/08-mob-title.png' });
  await mob.click('[data-diff="easy"]'); await mob.click('#m-go'); await mob.waitForTimeout(400);
  await mob.screenshot({ path: out + '/09-mob-desk.png', fullPage: true });
  const sw = await mob.evaluate(() => document.documentElement.scrollWidth);
  console.log('mobile scrollWidth', sw);
  console.log('errors', errs);
  await b.close();
})();
