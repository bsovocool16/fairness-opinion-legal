def profile_value(label, default=None):
    if not PROFILE.exists(): return default
    for line in PROFILE.read_text().splitlines():
        if label.lower() in line.lower() and ":" in line:
            v = line.split(":", 1)[1].strip()
            if v and "[PLACEHOLDER" not in v: return re.sub(r"^\[DEFAULT:\s*|\]$", "", v).strip()
    return default

def sec_ua():
    ua = os.environ.get("EDGAR_UA") or profile_value("Contact for SEC requests")
    if not ua: raise SystemExit("no SEC contact identity: run /fairness-opinion-legal:cold-start-interview or set EDGAR_UA to 'Name email'")
    return ua

_last = [0.0]
def get(url, params=None, headers=None, gap=None, tries=4, timeout=60):
    """GET with pacing (EDGAR_GAP seconds between requests, default 0.15 for data.sec.gov) and retries on 429/5xx."""
    import requests
    gap = float(os.environ.get("EDGAR_GAP", "0.15")) if gap is None else gap
    err = None
    for attempt in range(tries):
        wait = _last[0] + gap - time.time()
        if wait > 0: time.sleep(wait)
        try:
            r = requests.get(url, params=params, headers=headers or {}, timeout=timeout); _last[0] = time.time()
            if r.status_code in (429, 500, 502, 503, 504): time.sleep(2 * (attempt + 1)); err = f"HTTP {r.status_code}"; continue
            r.raise_for_status(); return r
        except Exception as e:
            err = str(e); time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f"GET {url} failed: {err}")

def sec_json(url): return get(url, headers={"User-Agent": sec_ua(), "Accept-Encoding": "gzip, deflate"}).json()

